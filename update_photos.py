import os
import re
import json

base_dir = os.path.dirname(os.path.abspath(__file__))
images_folder = os.path.join(base_dir, "images")
output_file = os.path.join(base_dir, "images.js")

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp", ".gif"}

numbered = []
for f in os.listdir(images_folder):
    full = os.path.join(images_folder, f)
    if os.path.isfile(full):
        stem, ext = os.path.splitext(f)
        if ext.lower() in IMAGE_EXTS and re.match(r"^(\d+)$", stem):
            numbered.append((int(stem), f))

numbered.sort(key=lambda item: item[0])
solo_files = [f for n, f in numbered if 1 <= n <= 6]
friend_group_files = [f for n, f in numbered if 7 <= n <= 13]
galaxy_files = [f for n, f in numbered if n >= 14]

def find_stem_file(stem_name):
    for f in os.listdir(images_folder):
        full = os.path.join(images_folder, f)
        if os.path.isfile(full):
            s, e = os.path.splitext(f)
            if s.lower() == stem_name.lower() and e.lower() in IMAGE_EXTS:
                return f
    return f"{stem_name}.jpg"

